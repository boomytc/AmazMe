"""Generate client HTTP/stream contracts from the Python public boundary."""

import argparse
import json
from pathlib import Path
from unittest.mock import Mock

from amazme_backend.contracts.events import Stream
from amazme_backend.host.service import Host
from amazme_backend.interfaces.http.application import application
from amazme_backend.platform.resources import package_resource

ROOT = Path(__file__).resolve().parents[1]


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(value) for value in schema["anyOf"])
    if "oneOf" in schema:
        return " | ".join(ts(value) for value in schema["oneOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    if kind == "object":
        if not schema.get("properties"):
            additional = schema.get("additionalProperties", True)
            return "Record<string, " + (ts(additional) if isinstance(additional, dict) else "unknown") + ">"
        required = schema.get("required", [])
        return "{\n" + "\n".join(f"  {json.dumps(key)}{'' if key in required else '?'}: {ts(value)};"
                                  for key, value in schema.get("properties", {}).items()) + "\n}"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated client contracts have drifted")
    args = parser.parse_args()

    def write(path: Path, content: str) -> None:
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"contract drift: {path.relative_to(ROOT.parent)}; run backend/tools/export_contracts.py")
        else:
            path.write_text(content)

    schema = Stream.model_json_schema()
    target = ROOT / "contracts"
    target.mkdir(exist_ok=True)
    text = json.dumps(schema, indent=2, ensure_ascii=False) + "\n"
    write(target / "events.schema.json", text)
    write(package_resource("web") / "events.schema.json", text)
    definitions = schema.pop("$defs", {})
    source = "// Generated by backend/tools/export_contracts.py; edit Python contracts.\n"
    source += "\n\n".join(f"export type {name} = {ts(value)};" for name, value in definitions.items())
    source += "\n\nexport type Stream = " + ts(schema) + ";\n"
    write(target / "events.d.ts", source)
    # Route construction does not start actors or access a profile. Runtime evidence
    # separately compares the live server's schema to this generated contract.
    api = application(Mock(spec=Host)).openapi()
    write(target / "openapi.json", json.dumps(api, indent=2, ensure_ascii=False) + "\n")
    models = {**api["components"]["schemas"], **definitions, "Stream": schema}
    generated = "// Generated by backend/tools/export_contracts.py; edit Python contracts.\n"
    generated += "\n\n".join(f"export type {name} = {ts(value)};" for name, value in models.items())
    generated += "\n\nexport interface ApiModels {\n"
    generated += "\n".join(f"  {name}: {name};" for name in models) + "\n}\n"
    operations = {}
    generated += "\nexport interface HttpOperations {\n"
    for path, methods in api["paths"].items():
        if not path.startswith("/api/"):
            continue
        for method, operation in methods.items():
            response = next(value for status, value in operation["responses"].items() if status.startswith("2"))
            response_schema = response.get("content", {}).get("application/json", {}).get("schema", {})
            body_schema = operation.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            path_fields = {p["name"]: p["schema"] for p in operation.get("parameters", []) if p["in"] == "path"}
            query_fields = {p["name"]: p["schema"] for p in operation.get("parameters", []) if p["in"] == "query"}
            path_schema = {"type": "object", "properties": path_fields, "required": list(path_fields)}
            query_schema = {"type": "object", "properties": query_fields,
                            "required": [p["name"] for p in operation.get("parameters", []) if p["in"] == "query" and p.get("required")]}
            key = method.upper() + " " + path
            operations[key] = {"response": response_schema, "body": body_schema}
            generated += f"  {json.dumps(key)}: {{ response: {ts(response_schema)}; path: {ts(path_schema)}; query: {ts(query_schema)}; body: {ts(body_schema) if body_schema else 'undefined'} }};\n"
    generated += "}\n"
    web = ROOT.parent / "packages/web/src"
    write(web / "python-contracts.ts", generated)
    # The browser validates before a value can enter its typed presentation state.
    write(web / "python-schema.json", json.dumps({"$defs": models, "operations": operations}, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    main()
