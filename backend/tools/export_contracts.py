"""Generate the WebSocket JSON Schema and TypeScript declarations from Python types."""

import json
from pathlib import Path

from amazme_backend.contracts import Stream

ROOT = Path(__file__).resolve().parents[1]


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(value) for value in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    if kind == "object":
        required = schema.get("required", [])
        return "{\n" + "\n".join(f"  {key}{'' if key in required else '?'}: {ts(value)};"
                                  for key, value in schema.get("properties", {}).items()) + "\n}"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}[kind]


def main():
    schema = Stream.model_json_schema()
    target = ROOT / "contracts"
    target.mkdir(exist_ok=True)
    text = json.dumps(schema, indent=2, ensure_ascii=False) + "\n"
    (target / "events.schema.json").write_text(text)
    (ROOT / "src/amazme_backend/web/events.schema.json").write_text(text)
    definitions = schema.pop("$defs", {})
    source = "// Generated by backend/tools/export_contracts.py; edit Python contracts.\n"
    source += "\n\n".join(f"export type {name} = {ts(value)};" for name, value in definitions.items())
    source += "\n\nexport type Stream = " + ts(schema) + ";\n"
    (target / "events.d.ts").write_text(source)


if __name__ == "__main__":
    main()
